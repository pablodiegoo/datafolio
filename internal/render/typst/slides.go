type logicalSlide struct {
	Index          int
	Title          string
	Kicker         string
	IsCover        bool
	IsBibliography bool
	TitleBlock     *doc.HeadingBlock
	Blocks         []doc.Block
	Header         doc.SlideChromeOverride
	Footer         doc.SlideChromeOverride
}

// RenderSlides compiles a SourceDocument into 16:9 widescreen Typst source for the `slides` Format.
func RenderSlides(d *doc.SourceDocument, cfg config.Config, tok school.SchoolTokens, labels school.Labels, opts RenderOptions) (string, error) {
	if d == nil {
		return "", fmt.Errorf("cannot render nil SourceDocument")
	}

	title := ResolveTitle(d)
	bibEntries, mappedBibPath, hasBib, cslArg, err := ResolveBibliographyAssets(d, cfg, opts)
	if err != nil {
		return "", err
	}

	slides := buildLogicalSlides(d, title, hasBib && HasCitedEntries(d.Citations, bibEntries), fallbackStr(labels.References, "References"))
	mainRatio, gapRatio, marginRatio := NormalizedColumnRatios(tok)

	var b strings.Builder
	b.WriteString("// Generated by DataFolio (slides format)\n")
	EmitSchoolPreamble(&b, tok, labels)
	b.WriteString("#let df-page-w = 254mm\n")
	b.WriteString("#let df-page-h = 142.875mm\n")
	b.WriteString("#let df-outer-x = 14mm\n")
	b.WriteString("#let df-top-margin = 15mm\n")
	b.WriteString("#let df-bottom-margin = 14mm\n")
	b.WriteString("#let df-printable-w = df-page-w - 2 * df-outer-x\n")
	fmt.Fprintf(&b, "#let df-main-w = df-printable-w * %.4f\n", mainRatio)
	fmt.Fprintf(&b, "#let df-gap-w = df-printable-w * %.4f\n", gapRatio)
	fmt.Fprintf(&b, "#let df-margin-w = df-printable-w * %.4f\n", marginRatio)
	b.WriteString("#let df-sec-level = 1\n\n")

	EmitTypstHelpers(&b)
	emitSlideHelpers(&b)

	headerExpr := BuildChromeExpr(cfg.Header, true, d, title, "df-printable-w")
	footerExpr := BuildChromeExpr(cfg.Footer, false, d, title, "df-printable-w")

	b.WriteString("#set page(\n")
	b.WriteString("  width: df-page-w,\n")
	b.WriteString("  height: df-page-h,\n")
	b.WriteString("  fill: df-paper,\n")
	b.WriteString("  margin: (\n")
	b.WriteString("    left: df-outer-x,\n")
	b.WriteString("    right: df-outer-x + df-gap-w + df-margin-w,\n")
	b.WriteString("    top: df-top-margin,\n")
	b.WriteString("    bottom: df-bottom-margin,\n")
	b.WriteString("  ),\n")
	b.WriteString("  header-ascent: 8pt,\n")
	b.WriteString("  footer-descent: 8pt,\n")
	fmt.Fprintf(&b, "  header: %s,\n", headerExpr)
	fmt.Fprintf(&b, "  footer: %s,\n", footerExpr)
	b.WriteString(")\n\n")

	EmitLanguageSetText(&b, cfg.Lang, "11pt")
	emitSlideShowRules(&b)

	ctx := &RenderContext{
		Doc:               d,
		Cfg:               cfg,
		Tok:               tok,
		Labels:            labels,
		BibEntries:        bibEntries,
		Opts:              opts,
		TopLevel:          true,
		RenderedSidenotes: make(map[string]bool),
		SectionLevel:      1,
		HasBibliography:   hasBib,
	}

	for _, sl := range slides {
		if err := renderLogicalSlide(&b, sl, d, cfg, title, mappedBibPath, cslArg, ctx); err != nil {
			return "", err
		}
	}

	return b.String(), nil
}

func emitSlideHelpers(b *strings.Builder) {
	b.WriteString(`#let df-slide-header(kicker, title-node) = df-wide[
  #block(width: 100%, below: 0.7em, inset: (bottom: 0.4em), stroke: (bottom: 0.85pt + df-rule-strong))[
    #if kicker != "" [
      #text(font: df-font-sans, size: 8pt, weight: "semibold", fill: df-accent, tracking: 0.12em)[#upper(kicker)]#linebreak()
      #v(0.18em)
    ]
    #if title-node != none [
      #title-node
    ]
  ]
]

`)
}

func emitSlideShowRules(b *strings.Builder) {
	b.WriteString("#set par(leading: 0.58em, spacing: 0.85em, justify: false)\n")
	b.WriteString("#set heading(numbering: none)\n")
	b.WriteString("#show heading.where(level: 1): set block(above: 0pt, below: 0pt)\n")
	b.WriteString("#show heading.where(level: 1): it => text(size: 18.5pt, weight: \"medium\", fill: df-ink)[#it.body]\n")
	b.WriteString("#show heading.where(level: 2): set block(sticky: true, above: 0.8em, below: 0.4em)\n")
	b.WriteString("#show heading.where(level: 2): set text(size: 13pt, weight: \"medium\", fill: df-ink)\n")
	b.WriteString("#show heading.where(level: 3): set block(sticky: true, above: 0.65em, below: 0.35em)\n")
	b.WriteString("#show heading.where(level: 3): set text(size: 11.5pt, weight: \"medium\", style: \"italic\", fill: df-ink)\n")
	EmitSharedShowRules(b, 1, "0.7em")
}

func buildLogicalSlides(d *doc.SourceDocument, deckTitle string, appendBib bool, bibTitle string) []logicalSlide {
	var slides []logicalSlide
	bodySlides := d.Slides

	if hasCoverMetadata(d.Meta) {
		cover := logicalSlide{
			Index:   1,
			Title:   deckTitle,
			Kicker:  strings.TrimSpace(d.Meta.Kicker),
			IsCover: true,
		}
		if len(bodySlides) > 0 && isCoverIntroSlide(bodySlides[0]) {
			intro := bodySlides[0]
			if strings.TrimSpace(intro.Kicker) != "" {
				cover.Kicker = strings.TrimSpace(intro.Kicker)
			}
			cover.Blocks = intro.Blocks
			cover.Header = intro.Header
			cover.Footer = intro.Footer
			bodySlides = bodySlides[1:]
		}
		slides = append(slides, cover)
	}

	for _, s := range bodySlides {
		titleBlock, bodyBlocks, slideTitle := extractSlideHeading(s)
		slides = append(slides, logicalSlide{
			Index:      len(slides) + 1,
			Title:      slideTitle,
			Kicker:     strings.TrimSpace(s.Kicker),
			TitleBlock: titleBlock,
			Blocks:     bodyBlocks,
			Header:     s.Header,
			Footer:     s.Footer,
		})
	}

	if len(slides) == 0 {
		slides = append(slides, logicalSlide{
			Index: 1,
			Title: deckTitle,
		})
	}

	if appendBib {
		slides = append(slides, logicalSlide{
			Index:          len(slides) + 1,
			Title:          bibTitle,
			IsBibliography: true,
		})
	}
	return slides
}

func hasCoverMetadata(m doc.Metadata) bool {
	return strings.TrimSpace(m.Title) != "" ||
		strings.TrimSpace(m.Subtitle) != "" ||
		strings.TrimSpace(m.Kicker) != "" ||
		strings.TrimSpace(m.Author) != "" ||
		strings.TrimSpace(m.Date) != ""
}

func isCoverIntroSlide(s doc.Slide) bool {
	for _, blk := range s.Blocks {
		switch blk.(type) {
		case *doc.ParagraphBlock, *doc.MarginNoteBlock, *doc.BlockquoteBlock, *doc.ListBlock:
			continue
		default:
			return false
		}
	}
	return true
}

func extractSlideHeading(s doc.Slide) (*doc.HeadingBlock, []doc.Block, string) {
	if len(s.Blocks) > 0 {
		if h, ok := s.Blocks[0].(*doc.HeadingBlock); ok {
			title := strings.TrimSpace(doc.InlinesPlainText(h.Inlines))
			if title == "" {
				title = strings.TrimSpace(s.Title)
			}
			return h, s.Blocks[1:], title
		}
	}
	title := strings.TrimSpace(s.Title)
	if title == "" {
		title = strings.TrimSpace(s.Kicker)
	}
	return nil, s.Blocks, title
}

func renderLogicalSlide(
	b *strings.Builder,
	sl logicalSlide,
	d *doc.SourceDocument,
	cfg config.Config,
	deckTitle string,
	mappedBibPath string,
	cslArg string,
	ctx *RenderContext,
) error {
	var pageArgs []string
	if sl.Header.Set {
		merged := mergeSlideChrome(cfg.Header, sl.Header, sl.Index == 1)
		pageArgs = append(pageArgs, fmt.Sprintf("header: %s", BuildChromeExpr(merged, true, d, deckTitle, "df-printable-w")))
	}
	if sl.Footer.Set {
		merged := mergeSlideChrome(cfg.Footer, sl.Footer, sl.Index == 1)
		pageArgs = append(pageArgs, fmt.Sprintf("footer: %s", BuildChromeExpr(merged, false, d, deckTitle, "df-printable-w")))
	}
	if len(pageArgs) > 0 {
		fmt.Fprintf(b, "#page(%s)[\n", strings.Join(pageArgs, ", "))
	} else {
		b.WriteString("#page[\n")
	}

	emitSlideBoundaryMarker(b, "start", sl.Index, sl.Title)

	switch {
	case sl.IsCover:
		coverMeta := d.Meta
		if sl.Kicker != "" {
			coverMeta.Kicker = sl.Kicker
		}
		EmitCoverBlock(b, coverMeta, deckTitle, "10%", true)
		if len(sl.Blocks) > 0 {
			b.WriteString("#v(0.8em)\n")
			coverCtx := *ctx
			coverCtx.MinBodyHeadingLevel = 2
			if err := RenderBlocks(b, sl.Blocks, &coverCtx); err != nil {
				return err
			}
		}
	case sl.IsBibliography:
		b.WriteString("#df-slide-header(\"\", [#heading(level: 1, outlined: true)[#df-label-references]])\n")
		EmitBibliography(b, mappedBibPath, cslArg, false)
	default:
		if sl.Kicker != "" || sl.TitleBlock != nil {
			titleNode := "none"
			if sl.TitleBlock != nil {
				var tb strings.Builder
				tb.WriteString("[#heading(level: 1, outlined: true)[")
				if err := RenderInlines(&tb, sl.TitleBlock.Inlines, ctx); err != nil {
					return err
				}
				tb.WriteByte(']')
				if sl.TitleBlock.ID != "" {
					fmt.Fprintf(&tb, "#label(%s)", TypstString("heading-"+sl.TitleBlock.ID))
				}
				tb.WriteByte(']')
				titleNode = tb.String()
			}
			fmt.Fprintf(b, "#df-slide-header(%s, %s)\n", TypstString(sl.Kicker), titleNode)
		}
		if len(sl.Blocks) > 0 {
			slideCtx := *ctx
			slideCtx.MinBodyHeadingLevel = 2
			slideCtx.FullWidthColumns = !blocksHaveMarginAnnotations(sl.Blocks)
			if err := RenderBlocks(b, sl.Blocks, &slideCtx); err != nil {
				return err
			}
		}
	}

	emitSlideBoundaryMarker(b, "end", sl.Index, sl.Title)
	b.WriteString("]\n\n")
	return nil
}

func emitSlideBoundaryMarker(b *strings.Builder, kind string, index int, title string) {
	fmt.Fprintf(b, "#context [#metadata((kind: %s, index: %d, title: %s, page: here().page())) %s]\n",
		TypstString(kind), index, TypstString(title), SlideMarkerSelector)
}

func mergeSlideChrome(base config.ChromeSpec, ov doc.SlideChromeOverride, isFirstSlide bool) config.ChromeSpec {
	if !ov.Set {
		return base
	}
	out := base
	if ov.Enabled != nil {
		out.Enabled = *ov.Enabled
	}
	if !out.Enabled {
		return out
	}
	if ov.ReplaceAllSlots {
		out.Left = ov.Left
		out.Center = ov.Center
		out.Right = ov.Right
	} else {
		if ov.HasLeft {
			out.Left = ov.Left
		}
		if ov.HasCenter {
			out.Center = ov.Center
		}
		if ov.HasRight {
			out.Right = ov.Right
		}
	}
	if ov.Rule != nil {
		out.Rule = *ov.Rule
	}
	if ov.SkipFirst != nil {
		out.SkipFirst = *ov.SkipFirst
	} else if isFirstSlide {
		out.SkipFirst = false
	}
	return out
}

func blocksHaveMarginAnnotations(blocks []doc.Block) bool {
	found := false
	doc.WalkBlocks(blocks, func(blk doc.Block) {
		if found {
			return
		}
		switch node := blk.(type) {
		case *doc.MarginNoteBlock:
			found = true
		case *doc.ParagraphBlock:
			found = inlinesHaveSidenoteRef(node.Inlines)
		case *doc.HeadingBlock:
			found = inlinesHaveSidenoteRef(node.Inlines)
		case *doc.TableBlock:
			for _, h := range node.Headers {
				if inlinesHaveSidenoteRef(h.Inlines) {
					found = true
					return
				}
			}
			for _, row := range node.Rows {
				for _, c := range row {
					if inlinesHaveSidenoteRef(c.Inlines) {
						found = true
						return
					}
				}
			}
		}
	})
	return found
}

func inlinesHaveSidenoteRef(inlines []doc.Inline) bool {
	found := false
	doc.WalkInlines(inlines, func(in doc.Inline) {
		if !found {
			if _, ok := in.(*doc.SidenoteRefInline); ok {
				found = true
			}
		}
	})
	return found
}
