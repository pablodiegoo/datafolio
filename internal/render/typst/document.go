// RenderDocument compiles a SourceDocument into complete Typst source for the `document` Format.
func RenderDocument(d *doc.SourceDocument, cfg config.Config, tok school.SchoolTokens, labels school.Labels, opts RenderOptions) (string, error) {
	if d == nil {
		return "", fmt.Errorf("cannot render nil SourceDocument")
	}

	title := ResolveTitle(d)
	secLevel := DetectMinHeadingLevel(d.Blocks)

	var bibEntries map[string]doc.BibEntry
	var mappedBibPath string
	hasBib := false
	if bibPath := ResolveBibPath(cfg.Bibliography, d.Dir); bibPath != "" {
		entries, err := doc.ParseBibFile(bibPath)
		if err != nil {
			return "", fmt.Errorf("bibliography %q: %w", cfg.Bibliography, err)
		}
		bibEntries = entries
		hasBib = true
		if opts.AssetMapper != nil {
			mappedBibPath, err = opts.AssetMapper(bibPath)
			if err != nil {
				return "", fmt.Errorf("bibliography %q: %w", cfg.Bibliography, err)
			}
		} else {
			mappedBibPath = bibPath
		}
	}

	cslArg, cslIsFile, err := ResolveCSL(cfg.CSL, d.Dir)
	if err != nil {
		return "", err
	}
	if cslIsFile && opts.AssetMapper != nil {
		cslArg, err = opts.AssetMapper(cslArg)
		if err != nil {
			return "", fmt.Errorf("csl %q: %w", cfg.CSL, err)
		}
	}

	mainRatio, gapRatio, marginRatio := normalizedColumnRatios(tok)
	pageWidth := "210mm"
	paperName := "a4"
	if strings.EqualFold(strings.TrimSpace(cfg.Paper), "letter") {
		paperName = "us-letter"
		pageWidth = "215.9mm"
	}

	typLang, typRegion := TypstLangRegion(cfg.Lang)

	var b strings.Builder
	b.WriteString("// Generated by DataFolio (document format)\n")
	EmitSchoolPreamble(&b, tok, labels)
	fmt.Fprintf(&b, "#let df-page-w = %s\n", pageWidth)
	b.WriteString("#let df-outer-x = 18mm\n")
	b.WriteString("#let df-top-margin = 24mm\n")
	b.WriteString("#let df-bottom-margin = 22mm\n")
	b.WriteString("#let df-printable-w = df-page-w - 2 * df-outer-x\n")
	fmt.Fprintf(&b, "#let df-main-w = df-printable-w * %.4f\n", mainRatio)
	fmt.Fprintf(&b, "#let df-gap-w = df-printable-w * %.4f\n", gapRatio)
	fmt.Fprintf(&b, "#let df-margin-w = df-printable-w * %.4f\n", marginRatio)
	fmt.Fprintf(&b, "#let df-sec-level = %d\n\n", secLevel)

	emitDocumentHelpers(&b)

	headerExpr := BuildChromeExpr(cfg.Header, true, d, title, "df-printable-w")
	footerExpr := BuildChromeExpr(cfg.Footer, false, d, title, "df-printable-w")

	b.WriteString("#set page(\n")
	fmt.Fprintf(&b, "  paper: %s,\n", TypstString(paperName))
	b.WriteString("  fill: df-paper,\n")
	b.WriteString("  margin: (\n")
	b.WriteString("    left: df-outer-x,\n")
	b.WriteString("    right: df-outer-x + df-gap-w + df-margin-w,\n")
	b.WriteString("    top: df-top-margin,\n")
	b.WriteString("    bottom: df-bottom-margin,\n")
	b.WriteString("  ),\n")
	fmt.Fprintf(&b, "  header: %s,\n", headerExpr)
	fmt.Fprintf(&b, "  footer: %s,\n", footerExpr)
	b.WriteString(")\n\n")

	if typRegion != "" {
		fmt.Fprintf(&b, "#set text(font: df-font-serif, fill: df-ink, size: 10.5pt, lang: %s, region: %s, number-width: \"tabular\")\n",
			TypstString(typLang), TypstString(typRegion))
	} else {
		fmt.Fprintf(&b, "#set text(font: df-font-serif, fill: df-ink, size: 10.5pt, lang: %s, number-width: \"tabular\")\n",
			TypstString(typLang))
	}

	emitDocumentShowRules(&b, secLevel)

	if cfg.Cover {
		emitCoverPage(&b, d.Meta, title)
	} else {
		emitMonographHeader(&b, d.Meta)
	}

	if cfg.TOC {
		b.WriteString("#outline(title: [#df-label-contents], indent: auto, depth: 3)\n")
		if cfg.Cover {
			b.WriteString("#pagebreak(weak: true)\n\n")
		} else {
			b.WriteString("#v(0.8em)\n#line(length: 100%, stroke: 0.5pt + df-rule)\n#v(1.0em)\n\n")
		}
	}

	ctx := &RenderContext{
		Doc:               d,
		Cfg:               cfg,
		Tok:               tok,
		Labels:            labels,
		BibEntries:        bibEntries,
		Opts:              opts,
		TopLevel:          true,
		RenderedSidenotes: make(map[string]bool),
		SectionLevel:      secLevel,
		HasBibliography:   hasBib,
	}

	if err := RenderBlocks(&b, d.Blocks, ctx); err != nil {
		return "", err
	}

	if hasBib && hasCitedEntries(d.Citations, bibEntries) {
		b.WriteByte('\n')
		if cslArg != "" {
			fmt.Fprintf(&b, "#bibliography(%s, title: [#df-label-references], style: %s)\n",
				TypstString(mappedBibPath), TypstString(cslArg))
		} else {
			fmt.Fprintf(&b, "#bibliography(%s, title: [#df-label-references])\n",
				TypstString(mappedBibPath))
		}
	}

	return b.String(), nil
}

func normalizedColumnRatios(tok school.SchoolTokens) (mainR, gapR, marginR float64) {
	mainR = ParsePercentRatio(tok.MainWidth, 0.65)
	gapR = ParsePercentRatio(tok.ColumnGap, 0.05)
	marginR = ParsePercentRatio(tok.MarginWidth, 0.30)
	total := mainR + gapR + marginR
	if total <= 0 {
		return 0.65, 0.05, 0.30
	}
	return mainR / total, gapR / total, marginR / total
}

func hasCitedEntries(citations []string, bibEntries map[string]doc.BibEntry) bool {
	for _, key := range citations {
		if _, ok := bibEntries[key]; ok {
			return true
		}
	}
	return false
}

func emitDocumentHelpers(b *strings.Builder) {
	b.WriteString(`#let df-section() = {
  let pg = here().page()
  let hs = query(heading.where(level: df-sec-level, outlined: true))
  if hs.len() == 0 {
    hs = query(heading.where(outlined: true))
  }
  let current = ""
  for h in hs {
    let hpg = h.location().page()
    if hpg < pg {
      current = h.body
    } else if hpg == pg {
      current = h.body
      break
    }
  }
  current
}

#let df-place-margin(body, align-offset: 0pt, page-origin: false) = context {
  let pos = here().position()
  let pg = pos.page
  let anchor-y = pos.y
  let prevs = query(selector(<df-margin-mark>).before(here()))
  let min-y = df-top-margin.to-absolute()
  for m in prevs {
    if m.value.page == pg and m.value.bottom > min-y {
      min-y = m.value.bottom
    }
  }
  let note-box = block(width: df-margin-w, breakable: false)[
    #set text(font: df-font-sans, size: 8.2pt, fill: df-ink-soft)
    #set par(leading: 0.52em, justify: false)
    #body
  ]
  let sz = measure(note-box)
  let max-y = page.height - df-bottom-margin.to-absolute() - sz.height
  let desired-y = anchor-y - align-offset.to-absolute()
  let target-y = calc.max(calc.min(desired-y, max-y), min-y)
  let bottom-y = target-y + sz.height + 5pt
  let dx = if page-origin { df-main-w + df-gap-w } else { (df-outer-x + df-main-w + df-gap-w).to-absolute() - pos.x }
  let dy = if page-origin { target-y - df-top-margin.to-absolute() } else { target-y - anchor-y }
  [#metadata((page: pg, bottom: bottom-y)) <df-margin-mark>]
  place(top + left, dx: dx, dy: dy, note-box)
}

#let df-sidenote(num, body) = {
  super[#text(fill: df-accent, weight: "semibold")[#num]]
  box(width: 0pt, height: 0pt)[
    #df-place-margin(align-offset: 0.7em)[
      #text(fill: df-accent, weight: "semibold")[#num. ]#body
    ]
  ]
}

#let df-margin-note(body) = {
  df-place-margin(align-offset: 0pt, page-origin: true, body)
}

#let df-inline-note(body) = block(
  width: 100%,
  inset: (left: 10pt, y: 6pt, right: 8pt),
  fill: df-paper-subtle,
  stroke: (left: 2pt + df-rule-strong),
)[
  #set text(font: df-font-sans, size: 8.8pt, fill: df-ink-soft)
  #body
]

#let df-wide(body) = {
  block(width: df-printable-w, breakable: true)[#body]
  context [#metadata((page: here().page(), bottom: here().position().y + 5pt)) <df-margin-mark>]
}

#let df-kpi(body) = block(
  width: 100%,
  inset: (y: 6pt),
  stroke: (top: df-booktabs-top + df-rule-strong, bottom: df-booktabs-top + df-rule-strong),
)[#body]

#let df-blockquote(body) = block(
  width: 100%,
  inset: (left: 10pt, y: 2pt),
  stroke: (left: 2pt + df-accent),
)[
  #set text(fill: df-ink-soft, style: "italic")
  #body
]

#let df-code-block(body) = block(
  width: 100%,
  inset: 8pt,
  fill: df-paper-subtle,
  stroke: 0.5pt + df-rule,
)[
  #set text(font: df-font-mono, size: 8.5pt, fill: df-ink)
  #body
]

`)
}

func emitDocumentShowRules(b *strings.Builder, secLevel int) {
	b.WriteString("#set par(leading: 0.65em, spacing: 1.0em, justify: false)\n")
	b.WriteString("#set heading(numbering: none)\n")
	b.WriteString("#show heading: set block(sticky: true, above: 1.4em, below: 0.65em)\n")
	b.WriteString("#show heading.where(level: 1): it => {\n")
	b.WriteString("  set text(size: 16pt, weight: \"medium\", fill: df-ink)\n")
	b.WriteString("  block(width: 100%, below: 0.45em, stroke: (bottom: 0.6pt + df-rule), inset: (bottom: 4pt))[#it]\n")
	b.WriteString("}\n")
	b.WriteString("#show heading.where(level: 2): it => {\n")
	b.WriteString("  set text(size: 13.5pt, weight: \"medium\", fill: df-ink)\n")
	b.WriteString("  block(width: 100%, below: 0.4em, stroke: (bottom: 0.5pt + df-rule), inset: (bottom: 3pt))[#it]\n")
	b.WriteString("}\n")
	b.WriteString("#show heading.where(level: 3): set text(size: 11.5pt, weight: \"medium\", style: \"italic\", fill: df-ink)\n")
	b.WriteString("#show raw.where(block: false): it => box(fill: df-paper-subtle, inset: (x: 2.5pt, y: 0pt), outset: (y: 1.5pt), stroke: 0.4pt + df-rule)[#text(font: df-font-mono, size: 8.8pt)[#it]]\n")
	b.WriteString("#show link: set text(fill: df-accent)\n")
	b.WriteString("#show figure: set block(above: 1.1em, below: 1.1em)\n")
	b.WriteString("#show figure.where(kind: table): set block(breakable: true)\n")
	b.WriteString("#show figure.where(kind: table): set figure.caption(position: top)\n")
	b.WriteString("#show figure.caption: set text(font: df-font-sans, size: 8.5pt, fill: df-ink-soft)\n")
	fmt.Fprintf(b, "#show bibliography: set heading(level: %d)\n\n", secLevel)
}

func emitCoverPage(b *strings.Builder, meta doc.Metadata, fallbackTitle string) {
	title := strings.TrimSpace(meta.Title)
	if title == "" {
		title = fallbackTitle
	}
	b.WriteString("#block(width: df-printable-w)[\n")
	b.WriteString("  #v(16%)\n")
	if meta.Kicker != "" {
		fmt.Fprintf(b, "  #text(font: df-font-sans, size: 9pt, weight: \"semibold\", fill: df-accent, tracking: 0.12em)[#upper(%s)]\n  #v(0.6em)\n",
			TypstString(meta.Kicker))
	}
	fmt.Fprintf(b, "  #text(size: 28pt, weight: \"medium\", fill: df-ink)[%s]\n", EscapeMarkup(title))
	if meta.Subtitle != "" {
		fmt.Fprintf(b, "  #v(0.6em)\n  #text(size: 14pt, style: \"italic\", fill: df-ink-soft)[%s]\n", EscapeMarkup(meta.Subtitle))
	}
	b.WriteString("  #v(1.6em)\n  #line(length: 100%, stroke: 1.5pt + df-rule-strong)\n  #v(1.0em)\n")
	if meta.Author != "" || meta.Date != "" {
		b.WriteString("  #text(font: df-font-sans, size: 10pt, fill: df-muted)[")
		if meta.Author != "" {
			b.WriteString(EscapeMarkup(meta.Author))
		}
		if meta.Author != "" && meta.Date != "" {
			b.WriteString("  ·  ")
		}
		if meta.Date != "" {
			b.WriteString(EscapeMarkup(meta.Date))
		}
		b.WriteString("]\n")
	}
	b.WriteString("]\n")
	b.WriteString("#pagebreak(weak: true)\n\n")
}

func emitMonographHeader(b *strings.Builder, meta doc.Metadata) {
	hasHeader := meta.Kicker != "" || meta.Title != "" || meta.Subtitle != "" || meta.Author != "" || meta.Date != ""
	if !hasHeader {
		return
	}
	b.WriteString("#block(width: 100%, below: 1.4em, inset: (bottom: 1.0em), stroke: (bottom: 1.125pt + df-rule-strong))[\n")
	if meta.Kicker != "" {
		fmt.Fprintf(b, "  #text(font: df-font-sans, size: 8pt, weight: \"semibold\", fill: df-accent, tracking: 0.12em)[#upper(%s)]#linebreak()\n  #v(0.35em)\n",
			TypstString(meta.Kicker))
	}
	if meta.Title != "" {
		fmt.Fprintf(b, "  #text(size: 22pt, weight: \"medium\", fill: df-ink)[%s]\n", EscapeMarkup(meta.Title))
	}
	if meta.Subtitle != "" {
		fmt.Fprintf(b, "  #v(0.3em)\n  #text(size: 12.5pt, style: \"italic\", fill: df-ink-soft)[%s]\n", EscapeMarkup(meta.Subtitle))
	}
	if meta.Author != "" || meta.Date != "" {
		b.WriteString("  #v(0.6em)\n  #text(font: df-font-sans, size: 9pt, fill: df-muted)[")
		if meta.Author != "" {
			b.WriteString(EscapeMarkup(meta.Author))
		}
		if meta.Author != "" && meta.Date != "" {
			b.WriteString(" · ")
		}
		if meta.Date != "" {
			b.WriteString(EscapeMarkup(meta.Date))
		}
		b.WriteString("]\n")
	}
	b.WriteString("]\n\n")
}
